#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { inspectDirectory, DEFAULT_ROOT } = require('./checkDatabaseDrafts');
const { buildRuleSeedSql } = require('./generateRuleSeedSql');
const { buildScoringProfileSeedSql } = require('./generateScoringProfileSeedSql');
const { PLAN_CATALOG, CATALOG_VERSION } = require('../domain/planCatalog');

function sqlLiteral(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function jsonLiteral(value) {
  return `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`;
}

function generatePlanEntitlementsSql() {
  const lines = [
    '-- GENERATED from server/domain/planCatalog.js by prepareStagingMigrations.js',
    `-- Plan Catalog Version: ${CATALOG_VERSION}`,
    '',
  ];

  const planEntries = [
    {
      plan: 'free',
      capabilities: [
        { capability: 'security_scan', enabled: true, monthlyLimit: PLAN_CATALOG.free.quotas.security_scan },
      ],
    },
    {
      plan: 'starter',
      capabilities: [
        { capability: 'security_scan', enabled: true, monthlyLimit: PLAN_CATALOG.starter.quotas.security_scan },
      ],
    },
    {
      plan: 'growth',
      capabilities: [
        { capability: 'security_scan', enabled: true, monthlyLimit: PLAN_CATALOG.growth.quotas.security_scan },
        { capability: 'repository_scan', enabled: true, monthlyLimit: null },
      ],
    },
    {
      plan: 'business',
      capabilities: [
        { capability: 'security_scan', enabled: true, monthlyLimit: null },
        { capability: 'repository_scan', enabled: true, monthlyLimit: null },
        { capability: 'browser_scan', enabled: true, monthlyLimit: null },
        { capability: 'ai_screening', enabled: true, monthlyLimit: null },
        { capability: 'ai_document_screening', enabled: true, monthlyLimit: null },
      ],
    },
  ];

  for (const entry of planEntries) {
    for (const cap of entry.capabilities) {
      const limitVal = cap.monthlyLimit === null ? 'null' : String(cap.monthlyLimit);
      const metadata = { catalogVersion: CATALOG_VERSION, source: 'plan_catalog' };
      lines.push(
        `insert into public.plan_entitlements (plan, capability, enabled, monthly_limit, metadata)` +
        ` values (${sqlLiteral(entry.plan)}, ${sqlLiteral(cap.capability)}, ${cap.enabled ? 'true' : 'false'}, ${limitVal}, ${jsonLiteral(metadata)})` +
        ` on conflict (plan, capability) do update set enabled = excluded.enabled, monthly_limit = excluded.monthly_limit, metadata = excluded.metadata, updated_at = now();`,
      );
    }
  }

  return `${lines.join('\n')}\n`;
}

function prepareStagingBundle({ databaseDir = DEFAULT_ROOT } = {}) {
  const inspection = inspectDirectory(databaseDir);
  if (!inspection.passed) {
    throw new Error(`Database drafts inspection failed: ${JSON.stringify(inspection.issues)}`);
  }

  const files = fs.readdirSync(databaseDir)
    .filter((name) => /^(\d{3})_[a-z0-9_]+_draft\.sql$/.test(name))
    .sort();

  const sections = [
    '-- =====================================================================',
    '-- GuardAI Dedicated Staging Consolidated Migration Bundle',
    '-- GENERATED BY server/scripts/prepareStagingMigrations.js',
    '-- DO NOT APPLY TO SHARED MULTI-TENANT SUPABASE PROJECTS',
    `-- Source: ${files.length} draft migrations validated`,
    '-- =====================================================================',
    '',
  ];

  for (const file of files) {
    const filePath = path.join(databaseDir, file);
    const content = fs.readFileSync(filePath, 'utf8');
    sections.push(
      '-- ---------------------------------------------------------------------',
      `-- Section: ${file}`,
      '-- ---------------------------------------------------------------------',
      content.trim(),
      '',
    );
  }

  sections.push(
    '-- ---------------------------------------------------------------------',
    '-- Canonical Plan Entitlements Seed (from server/domain/planCatalog.js)',
    '-- ---------------------------------------------------------------------',
    'begin;',
    generatePlanEntitlementsSql().trim(),
    'commit;',
    '',
  );

  sections.push(
    '-- ---------------------------------------------------------------------',
    '-- Canonical Versioned Rules Seed (from shared/rules/*.json)',
    '-- ---------------------------------------------------------------------',
    'begin;',
    buildRuleSeedSql().trim(),
    'commit;',
    '',
  );

  sections.push(
    '-- ---------------------------------------------------------------------',
    '-- Canonical Versioned Scoring Profiles Seed (from shared/scoring/*.json)',
    '-- ---------------------------------------------------------------------',
    'begin;',
    buildScoringProfileSeedSql().trim(),
    'commit;',
    '',
  );

  return {
    inspection,
    bundleSql: sections.join('\n'),
    fileCount: files.length,
  };
}

function main() {
  const args = process.argv.slice(2);
  const checkOnly = args.includes('--check');
  const stdoutOnly = args.includes('--stdout');
  const outputArgIndex = args.indexOf('--output');
  const outputPath = outputArgIndex !== -1 && args[outputArgIndex + 1] ? args[outputArgIndex + 1] : null;

  try {
    const bundle = prepareStagingBundle();
    if (checkOnly) {
      process.stdout.write(`Staging migration bundle check: PASS (${bundle.fileCount} drafts, inspection passed)\n`);
      return;
    }

    if (outputPath) {
      const resolved = path.resolve(process.cwd(), outputPath);
      fs.mkdirSync(path.dirname(resolved), { recursive: true });
      fs.writeFileSync(resolved, bundle.bundleSql, 'utf8');
      process.stdout.write(`Staging migration bundle written to ${resolved} (${bundle.fileCount} drafts)\n`);
      return;
    }

    if (stdoutOnly) {
      process.stdout.write(bundle.bundleSql);
      return;
    }

    process.stdout.write(`Staging migration bundle prepared successfully (${bundle.fileCount} drafts consolidated).\n`);
    process.stdout.write(`Use --check to verify, --stdout to pipe, or --output <file> to write.\n`);
  } catch (error) {
    process.stderr.write(`Error preparing staging migrations: ${error.message}\n`);
    process.exitCode = 1;
  }
}

if (require.main === module) {
  main();
}

module.exports = {
  generatePlanEntitlementsSql,
  prepareStagingBundle,
};
